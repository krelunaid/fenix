#!/usr/bin/env node
// Regenerates the embedded Lucide icon set used by the visual worker and the agent.
// Usage: node scripts/build-icon-set.mjs /path/to/lucide-clone
// Lucide is ISC-licensed (https://github.com/lucide-icons/lucide); the licence text is
// embedded in the generated module. Both workers deploy from their own folder, so the
// generated module is written twice and a test asserts the copies are identical.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) { console.error("usage: build-icon-set.mjs <lucide-clone>"); process.exit(1); }
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(src, "icons");
const license = readFileSync(join(src, "LICENSE"), "utf8").trim();

const icons = {};
for (const file of readdirSync(iconsDir).filter((f) => f.endsWith(".svg")).sort()) {
  const name = file.slice(0, -4);
  const svg = readFileSync(join(iconsDir, file), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const body = inner.replace(/\s*\n\s*/g, "").replace(/\s+\/>/g, "/>").replace(/>\s+</g, "><").trim();
  if (!body || /<script|on\w+=|javascript:/i.test(body)) continue;
  let tags = [];
  try { tags = JSON.parse(readFileSync(join(iconsDir, `${name}.json`), "utf8")).tags || []; } catch { /* no meta */ }
  tags = [...new Set(tags.map((t) => String(t).toLowerCase().trim()).filter(Boolean))];
  icons[name] = tags.length ? [body, tags.join(" ")] : [body];
}

const module = `// GENERATED by scripts/build-icon-set.mjs — do not edit by hand.
// Lucide icons (${Object.keys(icons).length}) — https://lucide.dev
/*
${license}
*/
export const LUCIDE_VERSION = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const LUCIDE = ${JSON.stringify(icons)};
`;
for (const target of ["workers/visual/icon-set.mjs", "workers/agent/icon-set.mjs"]) {
  writeFileSync(join(root, target), module);
  console.log(`${target}: ${Object.keys(icons).length} icons, ${(module.length / 1024).toFixed(0)} KB`);
}
